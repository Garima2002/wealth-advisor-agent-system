"""API request and response Data Transfer Objects (DTOs)."""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from app.models.anomaly import AnomalyFinding, SeverityLevel
from app.models.insights import AdvisoryInsight


class FinancialSummary(BaseModel):
    """Aggregate financial calculations across the evaluated period."""
    total_income: float = Field(..., description="Sum of all income credits")
    total_expenses: float = Field(..., description="Sum of all operational/living debits")
    net_cash_flow: float = Field(..., description="Total income minus total expenses")
    savings_rate_pct: Optional[float] = Field(
        default=None,
        description="Percentage of income saved (net_cash_flow / total_income * 100)"
    )
    category_breakdown: Dict[str, float] = Field(
        default_factory=dict,
        description="Spending categorized by label"
    )
    period_start: Optional[str] = Field(default=None, description="Earliest transaction date")
    period_end: Optional[str] = Field(default=None, description="Latest transaction date")
    transaction_count: int = Field(default=0, description="Total transactions processed")


class RiskIndicator(BaseModel):
    """Portfolio or behavioral risk signal."""
    indicator_name: str
    severity: SeverityLevel
    observed: str
    evidence: str


class AnalyzeRequest(BaseModel):
    """Request payload to initiate financial analysis."""
    client_id: str = Field(..., min_length=1, description="Target client identifier")
    client_profile: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Optional inline client JSON payload containing transactions and portfolio data"
    )
    mock_crm_failure: bool = Field(
        default=False,
        description="Simulate transient CRM failure to test partial fallback behavior"
    )
    mock_crm_timeout: bool = Field(
        default=False,
        description="Simulate CRM timeout to test timeout handling and degradation"
    )


class AnalysisResponse(BaseModel):
    """Comprehensive final report generated by OrchestratorAgent."""
    metadata: Dict[str, Any] = Field(
        ...,
        description="Execution metadata including session_id, correlation_id, timestamp, duration_ms"
    )
    client_id: str
    financial_summary: FinancialSummary
    anomaly_findings: List[AnomalyFinding] = Field(default_factory=list)
    risk_indicators: List[RiskIndicator] = Field(default_factory=list)
    actionable_insights: List[AdvisoryInsight] = Field(default_factory=list)
    data_quality_warnings: List[str] = Field(default_factory=list)
    human_review_status: Dict[str, int] = Field(
        default_factory=dict,
        description="Breakdown of findings by review state (pending, approved, rejected, overridden)"
    )
    system_status: Dict[str, Any] = Field(
        ...,
        description="System health, partial_result indicator, and execution stage traces"
    )


class HealthResponse(BaseModel):
    """System health status."""
    status: str = "ok"
    version: str = "1.0.0"
    timestamp: str
    uptime_status: str = "operational"


class ClientHistoryItem(BaseModel):
    """Individual historical summary entry for a client."""
    session_id: str
    timestamp: str
    net_cash_flow: float
    total_income: float
    total_expenses: float
    anomaly_count: int
    partial_result: bool


class ClientHistoryResponse(BaseModel):
    """Historical analysis summaries for a given client."""
    client_id: str
    count: int
    records: List[ClientHistoryItem]


class ErrorResponse(BaseModel):
    """Standardized error response schema."""
    error_code: str
    message: str
    details: Optional[Dict[str, Any]] = None
